                            # (    Hasing      )
                # the process of converting input data of any size into a fixed-length string of characters 
                # (called a hash value or digest) using a mathematical algorithm





                            # (Data Structures (Hash Tables): )
    # Programming languages use hashing to store and 
    # retrieve data quickly in constant time (O(1)) by mapping keys to specific array indices


#                       (Key Properties of Hashing)

# • Deterministic: The same input always produces the exact same hash output.

# • One-Way (Irreversible): You cannot reverse-engineer a hash to reveal the original data.

# • Fast Computation: The algorithm quickly calculates the hash value.

# • Avalanche Effect: Even a tiny change in the input (like altering a single letter)
#            creates a completely different hash output.

# • Collision Resistance: It is hard to find two different inputs that produce the same hash value.




