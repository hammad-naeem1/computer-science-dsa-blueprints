                    # (Fundamental Algorithms & Problem-Solving Paradigms)

# Algorithms are the operational processes applied directly to data structures to accomplish tasks.
#  The most crucial paradigms and categories include:


# ----------
#                       (      SEARCHING ALGORITHM             )
# • Searching Algorithms: Techniques to locate specific data within a structure, ranging from simple Linear Search
#  (\(O(N)\)) to optimized Binary Search (\(O(\log N)\)) which continuously divides a sorted dataset in half.


# ------------------

#                       (      SORTING ALGORITHM             )
# • Sorting Algorithms: Rearranging data into a specific order (numerical or alphabetical).
# Common examples include foundational sorts like Bubble Sort
# and highly efficient divide-and-conquer options like Merge Sort and Quick Sort.

# -------------------------
#                       (  • Divide and Conquer  ALGORITHM             )

# • Divide and Conquer: A strategy that recursively breaks a massive problem into smaller,
# manageable sub-problems, solves them independently, and combines their results.
# --------
#                       (      GREEDY ALGORITHM             )

# • Greedy Algorithms: An approach that makes the locally optimal choice at each individual step
# with the hope of finding a global optimum (e.g., Dijkstra's Shortest Path).

# ------------------
#                       (    Dynamic Programming ALGORITHM             )


# • Dynamic Programming (DP): An optimization method used for complex problems
# by breaking them down into overlapping sub-problems, solving each sub-problem just once, 
# and storing their solutions to avoid redundant calculations.