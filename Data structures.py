                                        # (Core Data Structures)

# Data structures dictate how data is arranged so it can be managed and retrieved efficiently. 
# They are split into two major categories:



# 1.                                (Linear Data Structures)

# Elements are arranged sequentially, making them simpler to implement but sometimes less efficient for complex datasets.
# example
# • Arrays: A fixed-size collection of items stored in contiguous memory locations. Great for fast access via index numbers.
# • Linked Lists: Elements (nodes) are scattered in memory, but each node points to the next one in the sequence.
# • Stacks: Follows a Last-In, First-Out (LIFO) behavior. Think of a stack of plates—you add (push) and remove (pop) from the top.
# • Queues: Follows a First-In, First-Out (FIFO) behavior. Similar to a line at a grocery store—the first person in line is served first.







# 2.                                 (Non-Linear Data Structures)

# Elements are arranged hierarchically or interconnectedly, making them ideal for representing complex relationships.
# example
# • Trees: A hierarchical structure consisting of a root node and children nodes (e.g., Binary Search Trees, Heaps).
# • Graphs: Network-like structures consisting of nodes (vertices) connected by lines (edges), used for modeling social networks or mapping routes.
# • Hash Tables: Structures that map unique "keys" to specific "values" to allow lightning-fast lookups.









